// Regenerates src/utils/fontCoverage.generated.ts from the PDF fonts' cmap tables.
// Run after changing the fonts in src/assets/fonts: node scripts/font-coverage.mjs
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

/** Code points that map to a real glyph (not .notdef) in a TrueType font. */
export const readCoverage = (buffer) => {
  const view = new DataView(buffer.buffer, buffer.byteOffset, buffer.byteLength);
  const numTables = view.getUint16(4);
  let cmap = -1;
  for (let i = 0; i < numTables; i += 1) {
    const record = 12 + i * 16;
    const tag = String.fromCharCode(...buffer.subarray(record, record + 4));
    if (tag === 'cmap') cmap = view.getUint32(record + 8);
  }
  if (cmap < 0) throw new Error('No cmap table');
  const subtables = [];
  for (let i = 0; i < view.getUint16(cmap + 2); i += 1) {
    const record = cmap + 4 + i * 8;
    subtables.push({ platform: view.getUint16(record), encoding: view.getUint16(record + 2), offset: cmap + view.getUint32(record + 4) });
  }
  const covered = new Set();
  const pick = subtables.find((t) => t.platform === 3 && t.encoding === 10) ?? subtables.find((t) => (t.platform === 3 && t.encoding === 1) || t.platform === 0);
  const format = view.getUint16(pick.offset);
  if (format === 12) {
    const groups = view.getUint32(pick.offset + 12);
    for (let g = 0; g < groups; g += 1) {
      const at = pick.offset + 16 + g * 12;
      const start = view.getUint32(at), end = view.getUint32(at + 4), glyph = view.getUint32(at + 8);
      for (let code = start; code <= end; code += 1) if (glyph + (code - start) !== 0) covered.add(code);
    }
  } else if (format === 4) {
    const segX2 = view.getUint16(pick.offset + 6);
    const ends = pick.offset + 14, starts = ends + segX2 + 2, deltas = starts + segX2, rangeOffsets = deltas + segX2;
    for (let s = 0; s < segX2 / 2; s += 1) {
      const end = view.getUint16(ends + s * 2), start = view.getUint16(starts + s * 2);
      const delta = view.getInt16(deltas + s * 2), rangeOffsetAt = rangeOffsets + s * 2, rangeOffset = view.getUint16(rangeOffsetAt);
      for (let code = start; code <= end && code !== 0xffff; code += 1) {
        let glyph;
        if (rangeOffset === 0) glyph = (code + delta) & 0xffff;
        else {
          const raw = view.getUint16(rangeOffsetAt + rangeOffset + (code - start) * 2);
          glyph = raw === 0 ? 0 : (raw + delta) & 0xffff;
        }
        if (glyph !== 0) covered.add(code);
      }
    }
  } else throw new Error(`Unsupported cmap format ${format}`);
  return covered;
};

export const toRanges = (codes) => {
  const sorted = [...codes].sort((a, b) => a - b);
  const ranges = [];
  for (const code of sorted) {
    const last = ranges[ranges.length - 1];
    if (last && code === last[1] + 1) last[1] = code;
    else ranges.push([code, code]);
  }
  return ranges;
};

export const fontFiles = ['NotoSans-Regular.ttf', 'NotoSans-Bold.ttf'].map((name) => new URL(`../src/assets/fonts/${name}`, import.meta.url));

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [first, ...rest] = fontFiles.map((url) => readCoverage(fs.readFileSync(url)));
  // A character is only safe if every weight has it.
  const shared = new Set([...first].filter((code) => rest.every((set) => set.has(code))));
  const ranges = toRanges(shared);
  const out = `// Generated by scripts/font-coverage.mjs from the PDF fonts. Do not edit by hand.\n// Code point ranges [start, end] that every embedded font weight can draw.\nexport const coveredRanges: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(ranges)};\n`;
  fs.writeFileSync(new URL('../src/utils/fontCoverage.generated.ts', import.meta.url), out);
  console.log(`${shared.size} code points in ${ranges.length} ranges`);
}
